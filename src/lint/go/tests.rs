use tree_sitter::Parser;

use super::{findings, nolint_ranges};
use crate::language::Language;
use crate::limits::Preset;
use crate::lint::LintFinding;

const INEFFASSIGN_SOURCE: &str = include_str!("fixtures/ineffassign.go");
const INEFFASSIGN_EXPECTED: &str = include_str!("fixtures/ineffassign.golangci");
const NOLINT_SOURCE: &str = include_str!("fixtures/nolint.go");
const NOLINT_EXPECTED: &str = include_str!("fixtures/nolint.golangci");
const LINTER: &str = "ineffassign";

fn lints(source: &str) -> Vec<LintFinding> {
    let mut parser = Parser::new();
    parser
        .set_language(&tree_sitter_go::LANGUAGE.into())
        .expect("la gramática de Go carga");
    let tree = parser.parse(source, None).expect("el archivo se parsea");
    findings(
        tree.root_node(),
        source.as_bytes(),
        Preset::Strict.limits(Language::Go, false),
    )
}

fn rendered(found: &[LintFinding]) -> Vec<String> {
    found
        .iter()
        .map(|finding| format!("{}:{} {}", finding.line, finding.column, finding.subject))
        .collect()
}

#[test]
fn ineffassign_matches_golangci_lint_on_the_fixture() {
    let expected: Vec<String> = INEFFASSIGN_EXPECTED.lines().map(str::to_owned).collect();
    assert_eq!(rendered(&lints(INEFFASSIGN_SOURCE)), expected);
}

#[test]
fn generated_files_are_skipped() {
    let source =
        "// Code generated by stringer. DO NOT EDIT.\n\npackage a\n\nfunc f() {\n\tx := 1\n\tx = 2\n}\n";
    assert_eq!(lints(source), Vec::new());
}

#[test]
fn a_header_after_the_package_clause_still_marks_the_file_as_generated() {
    let source = "package a\n\n// autogenerated file\n\nfunc f() {\n\tx := 1\n\tx = 2\n}\n";
    assert_eq!(lints(source), Vec::new());
}

#[test]
fn files_with_syntax_errors_are_skipped() {
    let source = "package a\n\nfunc f() {\n\tx := 1\n\tx = 2\n";
    assert_eq!(lints(source), Vec::new());
}

#[test]
fn a_comment_after_the_first_declaration_does_not_mark_the_file_as_generated() {
    let source = "package a\n\nfunc f() {\n\tx := 1\n\tx = 2\n}\n\n// Code generated elsewhere\n";
    assert_eq!(rendered(&lints(source)), ["4:2 x", "5:2 x"]);
}

fn unsuppressed(source: &str) -> Vec<String> {
    let ranges = nolint_ranges(source);
    let kept: Vec<LintFinding> = lints(source)
        .into_iter()
        .filter(|finding| {
            !ranges.iter().any(|range| {
                (range.line..=range.last_line).contains(&finding.line)
                    && (range.linters.is_empty() || range.linters.iter().any(|linter| linter == LINTER))
            })
        })
        .collect();
    rendered(&kept)
}

#[test]
fn nolint_ranges_match_golangci_lint_on_the_fixture() {
    let expected: Vec<String> = NOLINT_EXPECTED.lines().map(str::to_owned).collect();
    assert_eq!(unsuppressed(NOLINT_SOURCE), expected);
}

#[test]
fn nolint_before_the_package_clause_covers_the_whole_file() {
    let source = "//nolint:ineffassign
package a

func f() {
	x := 1
	x = 2
}
";
    assert_eq!(unsuppressed(source), Vec::<String>::new());
}

#[test]
fn nolint_keeps_its_reason_and_linters() {
    let ranges = nolint_ranges(
        "package a

var x = 1 //nolint:ineffassign,ErrCheck // lo pide la API
",
    );
    let range = ranges.first().expect("hay un nolint");
    assert_eq!(range.linters, ["ineffassign", "errcheck"]);
    assert_eq!(range.reason, "lo pide la API");
    assert_eq!((range.line, range.last_line), (3, 3));
}
