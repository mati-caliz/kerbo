use super::violations;
use crate::rules::{MigrationRule, RuleId};

const LOCKING_RULES: [MigrationRule; 9] = [
    MigrationRule::RequireConcurrentIndexCreation,
    MigrationRule::RequireConcurrentIndexDeletion,
    MigrationRule::AddingRequiredField,
    MigrationRule::AddingNotNullableField,
    MigrationRule::ChangingColumnType,
    MigrationRule::RenamingColumn,
    MigrationRule::RenamingTable,
    MigrationRule::BanDropColumn,
    MigrationRule::BanDropTable,
];

fn found(source: &str) -> Vec<(MigrationRule, usize, String)> {
    violations(source, 1)
        .into_iter()
        .filter_map(|violation| {
            let RuleId::Migration(rule) = violation.rule else {
                panic!("regla inesperada {:?}", violation.rule);
            };
            LOCKING_RULES
                .contains(&rule)
                .then_some((rule, violation.line, violation.subject))
        })
        .collect()
}

const SQUAWK_SAMPLE: &str = "ALTER TABLE t ADD CONSTRAINT c CHECK (col IS NOT NULL) NOT VALID;
ALTER TABLE t VALIDATE CONSTRAINT c;
ALTER TABLE t ALTER COLUMN col SET NOT NULL;
CREATE TABLE \"Users\" (id int);
CREATE INDEX i ON \"Users\" (id);
CREATE INDEX j ON public.\"Users\" (id);
CREATE INDEX k ON users (id);
ALTER TABLE x
  ADD COLUMN a int NOT NULL,
  ADD b int NOT NULL DEFAULT 1,
  DROP COLUMN c, DROP d,
  ALTER COLUMN e TYPE text,
  ALTER f SET DATA TYPE bigint,
  RENAME COLUMN g TO h;
ALTER TABLE x RENAME TO y;
ALTER TABLE x RENAME h TO i;
DROP TABLE a, b;
DROP INDEX CONCURRENTLY q;
DROP INDEX r;
COMMIT;
CREATE TABLE z (id int);
CREATE INDEX zz ON z (id);
ALTER TABLE z ADD COLUMN q int GENERATED ALWAYS AS (id * 2) STORED NOT NULL;
ALTER TABLE z ADD COLUMN w int NOT NULL GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE z ADD COLUMN pk int PRIMARY KEY;
";

#[test]
fn reports_what_squawk_reports_with_assume_in_transaction() {
    let lines: Vec<(MigrationRule, usize)> = found(SQUAWK_SAMPLE)
        .into_iter()
        .map(|(rule, line, _)| (rule, line))
        .collect();
    assert_eq!(
        lines,
        vec![
            (MigrationRule::RequireConcurrentIndexCreation, 6),
            (MigrationRule::RequireConcurrentIndexCreation, 7),
            (MigrationRule::AddingRequiredField, 9),
            (MigrationRule::BanDropColumn, 11),
            (MigrationRule::BanDropColumn, 11),
            (MigrationRule::ChangingColumnType, 12),
            (MigrationRule::ChangingColumnType, 13),
            (MigrationRule::RenamingColumn, 14),
            (MigrationRule::RenamingTable, 15),
            (MigrationRule::RenamingColumn, 16),
            (MigrationRule::BanDropTable, 17),
            (MigrationRule::RequireConcurrentIndexDeletion, 19),
            (MigrationRule::RequireConcurrentIndexCreation, 22),
        ]
    );
}

#[test]
fn names_the_table_column_or_index_involved() {
    let subjects: Vec<String> = found(SQUAWK_SAMPLE)
        .into_iter()
        .map(|(_, _, subject)| subject)
        .collect();
    assert_eq!(subjects[0], "public.Users");
    assert_eq!(subjects[2], "a");
    assert_eq!(subjects[4], "d");
    assert_eq!(subjects[8], "x");
    assert_eq!(subjects[10], "a, b");
    assert_eq!(subjects[11], "r");
}

#[test]
fn flags_set_not_null_without_a_validated_check() {
    let found =
        found("ALTER TABLE t ALTER COLUMN col SET NOT NULL;\nALTER TABLE \"t\" ALTER \"col\" SET NOT NULL;");
    assert_eq!(found.len(), 2);
    assert!(
        found
            .iter()
            .all(|(rule, _, _)| *rule == MigrationRule::AddingNotNullableField)
    );
}

#[test]
fn a_constraint_validated_in_an_earlier_migration_makes_set_not_null_safe() {
    assert_eq!(
        found("ALTER TABLE t VALIDATE CONSTRAINT other;\nALTER TABLE t ALTER col SET NOT NULL;"),
        Vec::new()
    );
}

#[test]
fn ignores_concurrent_operations_strings_and_constraints() {
    let source = "CREATE UNIQUE INDEX CONCURRENTLY IF NOT EXISTS a ON t (c);
DO $$ BEGIN DROP TABLE t; END $$;
ALTER TABLE t DROP CONSTRAINT fk, RENAME CONSTRAINT a TO b;
ALTER TABLE t ADD CONSTRAINT c UNIQUE (x);
-- DROP TABLE t;
INSERT INTO t VALUES ('DROP TABLE t;');";
    assert_eq!(found(source), Vec::new());
}

#[test]
fn tables_created_inside_an_explicit_transaction_are_exempt_until_commit() {
    let source = "COMMIT;\nCREATE TABLE a (id int);\nCREATE INDEX ON a (id);\nBEGIN;\nCREATE TABLE b (id int);\nCREATE INDEX ON b (id);\nCOMMIT AND CHAIN;\nCREATE INDEX ON b (id);";
    let lines: Vec<usize> = found(source).into_iter().map(|(_, line, _)| line).collect();
    assert_eq!(lines, vec![3, 8]);
}

#[test]
fn covers_types_views_and_foreign_tables() {
    let source = "ALTER TYPE address DROP ATTRIBUTE zip, ALTER ATTRIBUTE street TYPE text;
ALTER TYPE address RENAME ATTRIBUTE city TO town;
ALTER VIEW v RENAME COLUMN a TO b;
ALTER MATERIALIZED VIEW m RENAME b TO c;
ALTER VIEW v RENAME TO w;
ALTER FOREIGN TABLE f DROP COLUMN a, ADD COLUMN b int NOT NULL, RENAME TO g;
DROP FOREIGN TABLE f;";
    let rules: Vec<MigrationRule> = found(source).into_iter().map(|(rule, _, _)| rule).collect();
    assert_eq!(
        rules,
        vec![
            MigrationRule::BanDropColumn,
            MigrationRule::ChangingColumnType,
            MigrationRule::RenamingColumn,
            MigrationRule::RenamingColumn,
            MigrationRule::RenamingColumn,
            MigrationRule::BanDropColumn,
            MigrationRule::BanDropTable,
        ]
    );
}
