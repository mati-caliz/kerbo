use super::fields::NOW_DEFAULT;
use super::model::{Class, Field, FieldDefault, Flag};
use super::names::quoted;
use super::state::State;

const VARCHAR: &str = "varchar";
const TEXT: &str = "text";
const VARCHAR_TEMPLATE: &str = "varchar(%)";
const NUMERIC_TEMPLATE: &str = "numeric(%)";
const SLUG_LENGTH: &str = "50";
const EMAIL_LENGTH: &str = "254";
const URL_LENGTH: &str = "200";
const FILE_LENGTH: &str = "100";
const IDENTITY: &str = "GENERATED BY DEFAULT AS IDENTITY";
const EMPTY_STRING: &str = "''";
const MAX_RELATION_DEPTH: usize = 8;
const ARRAY_SUFFIX: &str = "[]";

pub const fn is_auto(class: Class) -> bool {
    matches!(class, Class::Auto | Class::BigAuto | Class::SmallAuto)
}

const fn is_positive(class: Class) -> bool {
    matches!(
        class,
        Class::PositiveInteger | Class::PositiveBigInteger | Class::PositiveSmallInteger
    )
}

const fn default_length(class: Class) -> Option<&'static str> {
    match class {
        Class::Slug => Some(SLUG_LENGTH),
        Class::Email => Some(EMAIL_LENGTH),
        Class::Url => Some(URL_LENGTH),
        Class::File => Some(FILE_LENGTH),
        Class::Auto
        | Class::BigAuto
        | Class::SmallAuto
        | Class::Char
        | Class::Text
        | Class::Binary
        | Class::Integer
        | Class::BigInteger
        | Class::SmallInteger
        | Class::PositiveInteger
        | Class::PositiveBigInteger
        | Class::PositiveSmallInteger
        | Class::Boolean
        | Class::DateTime
        | Class::Date
        | Class::Time
        | Class::Float
        | Class::Decimal
        | Class::Uuid
        | Class::Json
        | Class::Inet
        | Class::Duration
        | Class::HStore
        | Class::SearchVector
        | Class::Array
        | Class::ForeignKey
        | Class::OneToOne
        | Class::ManyToMany
        | Class::Other => None,
    }
}

const fn is_varchar(class: Class) -> bool {
    matches!(
        class,
        Class::Char | Class::Slug | Class::Email | Class::Url | Class::File
    )
}

const fn plain_type(class: Class) -> &'static str {
    match class {
        Class::Auto | Class::Integer | Class::PositiveInteger => "integer",
        Class::BigAuto | Class::BigInteger | Class::PositiveBigInteger => "bigint",
        Class::SmallAuto | Class::SmallInteger | Class::PositiveSmallInteger => "smallint",
        Class::Binary => "bytea",
        Class::Boolean => "boolean",
        Class::DateTime => "timestamp with time zone",
        Class::Date => "date",
        Class::Time => "time",
        Class::Float => "double precision",
        Class::Uuid => "uuid",
        Class::Json => "jsonb",
        Class::Inet => "inet",
        Class::Duration => "interval",
        Class::HStore => "hstore",
        Class::SearchVector => "tsvector",
        Class::Char
        | Class::Slug
        | Class::Email
        | Class::Url
        | Class::File
        | Class::Text
        | Class::Decimal
        | Class::Array
        | Class::ForeignKey
        | Class::OneToOne
        | Class::ManyToMany
        | Class::Other => TEXT,
    }
}

fn own_type(field: &Field) -> String {
    if is_varchar(field.class) {
        let length = field
            .max_length
            .as_deref()
            .or_else(|| default_length(field.class));
        return length.map_or_else(|| VARCHAR.to_owned(), |length| format!("{VARCHAR}({length})"));
    }
    if field.class == Class::Decimal {
        return format!(
            "numeric({}, {})",
            field.max_digits.as_deref().unwrap_or_default(),
            field.decimal_places.as_deref().unwrap_or_default()
        );
    }
    if let Some(element) = field.element.as_deref() {
        return format!("{}{ARRAY_SUFFIX}", own_type(element));
    }
    plain_type(field.class).to_owned()
}

pub fn db_type(field: &Field, state: &State) -> String {
    related_type(field, state, 0)
}

fn related_type(field: &Field, state: &State, depth: usize) -> String {
    let Some(relation) = field.relation.as_ref().filter(|_| field.is_foreign_key()) else {
        return own_type(field);
    };
    let target = state.resolve(&relation.to);
    let target_field = relation
        .to_field
        .as_deref()
        .and_then(|name| target.field(name))
        .or_else(|| target.primary_key());
    match target_field {
        Some(target_field) if target_field.is_foreign_key() && depth < MAX_RELATION_DEPTH => {
            related_type(target_field, state, depth.saturating_add(1))
        }
        Some(target_field) => own_type(target_field),
        None => plain_type(Class::BigAuto).to_owned(),
    }
}

pub fn type_template(field: &Field, state: &State) -> String {
    if field.is_foreign_key() {
        return db_type(field, state);
    }
    if is_varchar(field.class) {
        return VARCHAR_TEMPLATE.to_owned();
    }
    if field.class == Class::Decimal {
        return NUMERIC_TEMPLATE.to_owned();
    }
    own_type(field)
}

pub fn has_like_index(field: &Field, state: &State) -> bool {
    let column_type = db_type(field, state);
    (field.db_index() || field.unique())
        && (column_type.starts_with(VARCHAR) || column_type.starts_with(TEXT))
}

pub fn like_operator_class(field: &Field, state: &State) -> &'static str {
    if db_type(field, state).starts_with(VARCHAR) {
        "varchar_pattern_ops"
    } else {
        "text_pattern_ops"
    }
}

const fn empty_strings_allowed(class: Class) -> bool {
    matches!(
        class,
        Class::Char
            | Class::Slug
            | Class::Email
            | Class::Url
            | Class::File
            | Class::Text
            | Class::Binary
            | Class::Other
    )
}

pub fn effective_default(field: &Field) -> Option<String> {
    match &field.default {
        FieldDefault::Literal(literal) => Some(literal.clone()),
        FieldDefault::Unset
            if !field.null() && field.has(Flag::Blank) && empty_strings_allowed(field.class) =>
        {
            Some(EMPTY_STRING.to_owned())
        }
        FieldDefault::Unset if field.has(Flag::AutoNow) => Some(NOW_DEFAULT.to_owned()),
        FieldDefault::Null | FieldDefault::Unset => None,
    }
}

pub fn check(field: &Field) -> Option<String> {
    is_positive(field.class).then(|| format!("{} >= 0", quoted(&field.column())))
}

pub fn identity(field: &Field) -> Option<&'static str> {
    is_auto(field.class).then_some(IDENTITY)
}

pub fn definition(field: &Field, state: &State, include_default: bool) -> String {
    let mut parts = vec![db_type(field, state)];
    if let Some(database_default) = &field.db_default {
        parts.push(format!("DEFAULT {database_default}"));
    } else if include_default && let Some(default) = effective_default(field) {
        parts.push(format!("DEFAULT {default}"));
    }
    parts.push(if field.null() { "NULL" } else { "NOT NULL" }.to_owned());
    if field.primary_key() {
        parts.push("PRIMARY KEY".to_owned());
    } else if field.unique() {
        parts.push("UNIQUE".to_owned());
    }
    parts.join(" ")
}
