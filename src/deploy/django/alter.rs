use super::columns::{
    check, check_ignoring_column, db_type, effective_default, has_like_index, identity, is_auto,
    like_operator_class, type_template,
};
use super::deferred::{Kind, Statement, like_index_name};
use super::model::{Class, Field, FieldDefault};
use super::names::{index_name, quoted};
use super::schema::{Editor, constrained_target};
use super::state::State;

const VARCHAR: &str = "varchar";
const TEXT: &str = "text";
const PRIMARY_KEY_SUFFIX: &str = "_pk";
const CHECK_SUFFIX: &str = "_check";
const NULL: &str = "NULL";

#[derive(Debug, Clone, Copy)]
pub struct FieldChange<'change> {
    pub table: &'change str,
    pub old: &'change Field,
    pub new: &'change Field,
    pub before: &'change State,
    pub after: &'change State,
}

#[derive(Debug, Default)]
struct Actions {
    combined: Vec<String>,
    null: Vec<String>,
    post: Vec<String>,
}

impl FieldChange<'_> {
    fn old_type(&self) -> String {
        db_type(self.old, self.before)
    }

    fn new_type(&self) -> String {
        db_type(self.new, self.after)
    }

    fn column(&self) -> String {
        quoted(&self.new.column())
    }

    fn alter_table(&self, changes: &str) -> String {
        format!("ALTER TABLE {} {changes}", quoted(self.table))
    }

    fn changes_type(&self) -> bool {
        self.old_type() != self.new_type() || identity(self.old) != identity(self.new)
    }

    fn changes_indexed_text_type(&self) -> bool {
        let (old_type, new_type) = (self.old_type(), self.new_type());
        let leaves = |prefix: &str| old_type.starts_with(prefix) && !new_type.starts_with(prefix);
        (self.old.db_index() || self.old.unique()) && (leaves(VARCHAR) || leaves(TEXT))
    }

    fn needs_database_default(&self) -> bool {
        let new_default = effective_default(self.new);
        self.old.null()
            && !self.new.null()
            && self.new.db_default.is_none()
            && new_default.is_some()
            && (self.compares_json_adapters() || effective_default(self.old) != new_default)
    }

    fn compares_json_adapters(&self) -> bool {
        [self.old.class, self.new.class]
            .iter()
            .any(|class| matches!(class, Class::Json | Class::SanitizedJson))
    }

    fn four_way(&self) -> bool {
        (self.new.default != FieldDefault::Unset || self.new.db_default.is_some())
            && self.old.null()
            && !self.new.null()
    }
}

pub fn alter_field(editor: &mut Editor, change: FieldChange<'_>) {
    if change.old.is_many_to_many() || change.new.is_many_to_many() || change.old == change.new {
        return;
    }
    if change.changes_indexed_text_type() {
        drop_like_index(editor, change.table, &change.old.column());
    }
    rename_column(editor, change);
    let mut actions = type_actions(editor, change);
    default_actions(change, &mut actions);
    apply_actions(editor, change, actions);
    add_field_constraints(editor, change);
    if change.needs_database_default() {
        editor.execute(&change.alter_table(&format!("ALTER COLUMN {} DROP DEFAULT", change.column())));
    }
    alter_like_index(editor, change);
}

fn drop_like_index(editor: &mut Editor, table: &str, column: &str) {
    editor.execute(&format!(
        "DROP INDEX IF EXISTS {}",
        quoted(&like_index_name(table, column))
    ));
}

fn rename_column(editor: &mut Editor, change: FieldChange<'_>) {
    let (old, new) = (change.old.column(), change.new.column());
    if old == new {
        return;
    }
    editor.rename_column(change.table, &old, &new);
}

fn type_actions(editor: &mut Editor, change: FieldChange<'_>) -> Actions {
    let mut actions = Actions::default();
    if !change.changes_type() {
        return actions;
    }
    let column = change.column();
    let new_type = change.new_type();
    let using = if type_template(change.old, change.before) == type_template(change.new, change.after) {
        String::new()
    } else {
        format!(" USING {column}::{new_type}")
    };
    actions
        .combined
        .push(format!("ALTER COLUMN {column} TYPE {new_type}{using}"));
    let (old_auto, new_auto) = (is_auto(change.old.class), is_auto(change.new.class));
    if new_auto && !old_auto {
        actions.post.push(change.alter_table(&format!(
            "ALTER COLUMN {column} ADD GENERATED BY DEFAULT AS IDENTITY"
        )));
    } else if old_auto && !new_auto {
        editor.execute(&change.alter_table(&format!("ALTER COLUMN {column} DROP IDENTITY IF EXISTS")));
    }
    actions
}

fn apply_actions(editor: &mut Editor, change: FieldChange<'_>, mut actions: Actions) {
    let four_way = change.four_way();
    if !four_way {
        actions.combined.append(&mut actions.null);
    }
    if !actions.combined.is_empty() {
        editor.execute(&change.alter_table(&actions.combined.join(", ")));
    }
    if four_way && !actions.null.is_empty() {
        let default = change
            .new
            .db_default
            .clone()
            .or_else(|| effective_default(change.new))
            .unwrap_or_else(|| NULL.to_owned());
        editor.execute(&format!(
            "UPDATE {} SET {column} = {default} WHERE {column} IS NULL; SET CONSTRAINTS ALL IMMEDIATE",
            quoted(change.table),
            column = change.column()
        ));
        for null_action in &actions.null {
            editor.execute(&change.alter_table(null_action));
        }
    }
    for post_action in &actions.post {
        editor.execute(post_action);
    }
}

fn add_field_constraints(editor: &mut Editor, change: FieldChange<'_>) {
    let (old, new) = (change.old, change.new);
    let columns = [new.column()];
    if !new.primary_key() && new.unique() && (!old.unique() || old.primary_key()) {
        editor.run(&Statement::on_columns(change.table, &columns, Kind::Unique));
    }
    if (!old.db_index() || old.unique()) && new.db_index() && !new.unique() {
        editor.run(&Statement::on_columns(change.table, &columns, Kind::Index));
    }
    if new.primary_key() && !old.primary_key() {
        let name = index_name(change.table, &[&new.column()], PRIMARY_KEY_SUFFIX);
        editor.execute(&change.alter_table(&format!(
            "ADD CONSTRAINT {} PRIMARY KEY ({})",
            quoted(&name),
            change.column()
        )));
    }
    let had_constraint = old.is_foreign_key() && old.db_constraint();
    if !had_constraint && let Some((to_table, to_column)) = constrained_target(new, change.after) {
        editor.run(&Statement::on_columns(
            change.table,
            &columns,
            Kind::ForeignKey { to_table, to_column },
        ));
    }
    if let Some(condition) = check(new).filter(|_| check_ignoring_column(old) != check_ignoring_column(new)) {
        let name = index_name(change.table, &[&new.column()], CHECK_SUFFIX);
        editor.execute(&change.alter_table(&format!("ADD CONSTRAINT {} CHECK ({condition})", quoted(&name))));
    }
}

fn alter_like_index(editor: &mut Editor, change: FieldChange<'_>) {
    let (old, new) = (change.old, change.new);
    let gains_index = !(old.db_index() || old.unique()) && new.db_index();
    let gains_unique = !old.unique() && new.unique();
    if (gains_index || gains_unique || change.changes_indexed_text_type())
        && has_like_index(new, change.after)
    {
        editor.run(&Statement::on_columns(
            change.table,
            &[new.column()],
            Kind::Like(like_operator_class(new, change.after)),
        ));
    }
    if old.unique() && !(new.db_index() || new.unique()) {
        drop_like_index(editor, change.table, &old.column());
    }
}

fn default_actions(change: FieldChange<'_>, actions: &mut Actions) {
    let (old, new) = (change.old, change.new);
    let column = change.column();
    if let Some(database_default) = &new.db_default {
        if old.db_default.as_ref() != Some(database_default) {
            actions
                .combined
                .push(format!("ALTER COLUMN {column} SET DEFAULT {database_default}"));
        }
    } else if old.db_default.is_some() {
        actions
            .combined
            .push(format!("ALTER COLUMN {column} DROP DEFAULT"));
    }
    if change.needs_database_default()
        && let Some(default) = effective_default(new)
    {
        actions
            .combined
            .push(format!("ALTER COLUMN {column} SET DEFAULT {default}"));
    }
    if old.null() != new.null() {
        let null_change = if new.null() {
            "DROP NOT NULL"
        } else {
            "SET NOT NULL"
        };
        actions.null.push(format!("ALTER COLUMN {column} {null_change}"));
    }
}
