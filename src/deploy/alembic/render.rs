use std::collections::HashMap;

use tree_sitter::Node;

use super::calls::{Call, string_value};

const TYPE_NAMES: &[(&str, &str)] = &[
    ("Integer", "INTEGER"),
    ("INTEGER", "INTEGER"),
    ("INT", "INTEGER"),
    ("BigInteger", "BIGINT"),
    ("BIGINT", "BIGINT"),
    ("SmallInteger", "SMALLINT"),
    ("SMALLINT", "SMALLINT"),
    ("Text", "TEXT"),
    ("TEXT", "TEXT"),
    ("UnicodeText", "TEXT"),
    ("Boolean", "BOOLEAN"),
    ("BOOLEAN", "BOOLEAN"),
    ("Date", "DATE"),
    ("DATE", "DATE"),
    ("Time", "TIME WITHOUT TIME ZONE"),
    ("Interval", "INTERVAL"),
    ("INTERVAL", "INTERVAL"),
    ("Float", "FLOAT"),
    ("FLOAT", "FLOAT"),
    ("REAL", "REAL"),
    ("JSON", "JSON"),
    ("JSONB", "JSONB"),
    ("UUID", "UUID"),
    ("Uuid", "UUID"),
    ("LargeBinary", "BYTEA"),
    ("BYTEA", "BYTEA"),
    ("INET", "INET"),
    ("CIDR", "CIDR"),
    ("TSVECTOR", "TSVECTOR"),
];
const VARCHAR_TYPES: &[&str] = &["String", "VARCHAR", "Unicode"];
const CHAR_TYPES: &[&str] = &["CHAR", "NCHAR"];
const NUMERIC_TYPES: &[&str] = &["Numeric", "NUMERIC", "DECIMAL"];
const TIMESTAMP_TYPES: &[&str] = &["DateTime", "TIMESTAMP", "DATETIME"];
const ARRAY_TYPES: &[&str] = &["ARRAY"];
const ENUM_TYPES: &[&str] = &["Enum", "ENUM"];
const SERIALS: &[(&str, &str)] = &[
    ("INTEGER", "SERIAL"),
    ("BIGINT", "BIGSERIAL"),
    ("SMALLINT", "SMALLSERIAL"),
];
const TEXT_FUNCTIONS: &[&str] = &["text", "literal_column"];
const FUNCTION_NAMESPACE: &str = "func";
const SQL_LITERALS: &[(&str, &str)] = &[("true", "true"), ("false", "false"), ("null", "NULL")];

pub type Constants<'tree> = HashMap<&'tree str, Node<'tree>>;

#[derive(Debug, Clone, Default)]
pub struct Column {
    pub name: String,
    pub sql_type: String,
    pub constraints: Vec<String>,
    pub index: bool,
    pub primary_key: bool,
    pub autoincrement: Option<bool>,
}

pub fn quoted(name: &str) -> String {
    format!("\"{}\"", name.replace('"', "\"\""))
}

pub fn column(call: &Call<'_>, constants: &Constants<'_>) -> Option<Column> {
    let name = call.text_argument(0, "name")?;
    let mut column = Column {
        name,
        ..Column::default()
    };
    for argument in call.all_positional().into_iter().skip(1) {
        if let Some(sql_type) = type_sql(argument, call.source, constants) {
            column.sql_type = sql_type;
        } else if let Some(inner) = Call::parse(argument, call.source) {
            column.constraints.extend(column_clause(&inner));
        }
    }
    if let Some(sql_type) = call
        .keyword("type_")
        .and_then(|node| type_sql(node, call.source, constants))
    {
        column.sql_type = sql_type;
    }
    column.primary_key = call.keyword_is_true("primary_key");
    column.index = call.keyword_is_true("index");
    column.autoincrement = call.keyword("autoincrement").map(|value| value.kind() == "true");
    let not_null = call.keyword("nullable").map(|value| value.kind()) == Some("false");
    if not_null && !column.primary_key {
        column.constraints.push("NOT NULL".to_owned());
    }
    if let Some(default) = call
        .keyword("server_default")
        .and_then(|node| default_sql(node, call.source))
    {
        column.constraints.push(format!("DEFAULT {default}"));
    }
    if call.keyword_is_true("unique") {
        column.constraints.push("UNIQUE".to_owned());
    }
    Some(column)
}

pub fn make_serial(column: &mut Column, single_key: bool) {
    let automatic = column.autoincrement.unwrap_or(single_key);
    let eligible = automatic
        && (column.autoincrement == Some(true)
            || !column.constraints.iter().any(|clause| {
                clause.starts_with("REFERENCES")
                    || clause.starts_with("GENERATED")
                    || clause.starts_with("DEFAULT")
            }));
    if eligible
        && let Some((_, replacement)) = SERIALS.iter().find(|(integer, _)| *integer == column.sql_type)
    {
        column.sql_type = (*replacement).to_owned();
    }
}

fn column_clause(inner: &Call<'_>) -> Option<String> {
    match inner.method {
        "ForeignKey" => {
            let target = inner.text_argument(0, "column")?;
            let (table, column) = target.rsplit_once('.')?;
            Some(format!("REFERENCES {} ({})", quoted(table), quoted(column)))
        }
        "Computed" => {
            let expression = inner
                .positional(0)
                .and_then(|node| default_sql(node, inner.source))?;
            Some(format!("GENERATED ALWAYS AS ({expression}) STORED"))
        }
        "Identity" => Some("GENERATED BY DEFAULT AS IDENTITY".to_owned()),
        _ => None,
    }
}

pub fn render_column(column: &Column) -> String {
    let mut parts = vec![quoted(&column.name), column.sql_type.clone()];
    parts.extend(column.constraints.iter().cloned());
    parts.join(" ")
}

pub fn type_sql(node: Node<'_>, source: &[u8], constants: &Constants<'_>) -> Option<String> {
    let (name, call) = type_reference(node, source, constants)?;
    let arguments = |index: usize| {
        call.as_ref()
            .and_then(|call| call.positional(index))
            .and_then(|argument| argument.utf8_text(source).ok())
    };
    if let Some((_, fixed)) = TYPE_NAMES.iter().find(|(known, _)| *known == name) {
        return Some((*fixed).to_owned());
    }
    if VARCHAR_TYPES.contains(&name) {
        let length = arguments(0).or_else(|| {
            call.as_ref()
                .and_then(|call| call.keyword("length"))
                .and_then(|argument| argument.utf8_text(source).ok())
        });
        return Some(length.map_or_else(|| "VARCHAR".to_owned(), |length| format!("VARCHAR({length})")));
    }
    if CHAR_TYPES.contains(&name) {
        return Some(arguments(0).map_or_else(|| "CHAR".to_owned(), |length| format!("CHAR({length})")));
    }
    if NUMERIC_TYPES.contains(&name) {
        return Some(match (arguments(0), arguments(1)) {
            (Some(precision), Some(scale)) => format!("NUMERIC({precision}, {scale})"),
            (Some(precision), None) => format!("NUMERIC({precision})"),
            _ => "NUMERIC".to_owned(),
        });
    }
    if TIMESTAMP_TYPES.contains(&name) {
        let zoned = call.as_ref().is_some_and(|call| {
            call.keyword_is_true("timezone") || call.positional(0).is_some_and(|first| first.kind() == "true")
        });
        return Some(
            if zoned {
                "TIMESTAMP WITH TIME ZONE"
            } else {
                "TIMESTAMP WITHOUT TIME ZONE"
            }
            .to_owned(),
        );
    }
    if ARRAY_TYPES.contains(&name) {
        let item = call
            .as_ref()
            .and_then(|call| call.positional(0))
            .and_then(|item| type_sql(item, source, constants))?;
        return Some(format!("{item}[]"));
    }
    if ENUM_TYPES.contains(&name) {
        if let Some(enumeration) = call.as_ref().filter(|call| {
            call.keyword("native_enum")
                .is_some_and(|value| value.kind() == "false")
        }) {
            let longest = enumeration
                .all_positional()
                .into_iter()
                .filter_map(|label| string_value(label, source))
                .map(|label| label.chars().count())
                .max()
                .unwrap_or_default();
            let length = enumeration
                .keyword("length")
                .and_then(|value| value.utf8_text(source).ok().map(str::to_owned))
                .unwrap_or_else(|| longest.to_string());
            return Some(format!("VARCHAR({length})"));
        }
        return call
            .as_ref()
            .and_then(|call| call.keyword("name"))
            .and_then(|value| string_value(value, source))
            .map(|enum_name| quoted(&enum_name));
    }
    None
}

fn type_reference<'tree>(
    node: Node<'tree>,
    source: &'tree [u8],
    constants: &Constants<'tree>,
) -> Option<(&'tree str, Option<Call<'tree>>)> {
    if node.kind() == "identifier"
        && let Some(value) = node.utf8_text(source).ok().and_then(|name| constants.get(name))
    {
        return type_reference(*value, source, constants);
    }
    if node.kind() == "parenthesized_expression" {
        return crate::syntax::named_children(node)
            .into_iter()
            .find_map(|inner| type_reference(inner, source, constants));
    }
    let call = Call::parse(node, source);
    let reference = match &call {
        Some(_) => node.child_by_field_name("function")?,
        None => node,
    };
    let name = match reference.kind() {
        "attribute" => reference
            .child_by_field_name("attribute")?
            .utf8_text(source)
            .ok()?,
        "identifier" => reference.utf8_text(source).ok()?,
        _ => return None,
    };
    if name.starts_with(|first: char| first.is_ascii_uppercase()) {
        return Some((name, call));
    }
    let method_on_type = call.is_some() && reference.kind() == "attribute";
    reference
        .child_by_field_name("object")
        .filter(|_| method_on_type)
        .and_then(|object| type_reference(object, source, constants))
}

pub fn default_sql(node: Node<'_>, source: &[u8]) -> Option<String> {
    if let Some(text) = string_value(node, source) {
        return Some(format!("'{}'", text.replace('\'', "''")));
    }
    let call = Call::parse(node, source)?;
    if let Some((_, literal)) = SQL_LITERALS.iter().find(|(method, _)| *method == call.method) {
        return Some((*literal).to_owned());
    }
    if TEXT_FUNCTIONS.contains(&call.method) {
        return call.positional(0).and_then(|inner| string_value(inner, source));
    }
    let function = node.child_by_field_name("function")?;
    let namespace = function
        .child_by_field_name("object")
        .and_then(|object| object.utf8_text(source).ok());
    let is_sql_function = namespace.is_some_and(|namespace| {
        namespace == FUNCTION_NAMESPACE || namespace.rsplit('.').next() == Some(FUNCTION_NAMESPACE)
    });
    is_sql_function.then(|| format!("{}()", call.method))
}
