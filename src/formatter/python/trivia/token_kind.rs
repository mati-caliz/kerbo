const KEYWORDS: &[&str] = &[
    "and", "assert", "await", "break", "continue", "del", "elif", "except", "finally", "from", "global",
    "import", "is", "lazy", "nonlocal", "not", "or", "pass", "raise", "return", "try", "while", "match",
    "type", "case", "with", "yield",
];

// Las palabras clave que el formateador busca por su nombre tienen su variante; el resto es
// `Keyword`, que sólo importa por no ser un nombre.
pub fn keyword_or_name(text: &str) -> TokenKind {
    match text {
        "as" => TokenKind::As,
        "async" => TokenKind::Async,
        "class" => TokenKind::Class,
        "def" => TokenKind::Def,
        "else" => TokenKind::Else,
        "for" => TokenKind::For,
        "if" => TokenKind::If,
        "in" => TokenKind::In,
        "lambda" => TokenKind::Lambda,
        _ if KEYWORDS.contains(&text) => TokenKind::Keyword,
        _ => TokenKind::Name,
    }
}

