use std::collections::HashMap;
use std::path::{Path, PathBuf};

use super::{DIRECT_RULES, DirectFile, direct_reports, wants_direct_reports};
use crate::go_types::ModuleFacts;
use crate::language::Language;
use crate::limits::Preset;
use crate::rules::{FileIdentity, RuleId};
use crate::test_support::TempTree;

const SOURCE: &str = "package a\n\nimport \"io/ioutil\"\n\nfunc f() {\n\tioutil.ReadFile(\"a\")\n\tioutil.ReadFile(\"b\") //nolint:staticcheck // todavía no\n}\n";
const GENERATED: &str = "// Code generated by hand. DO NOT EDIT.\n\npackage a\n\nfunc g() {}\n";

fn identity(tree: &TempTree, name: &str) -> FileIdentity {
    FileIdentity {
        display: name.to_owned(),
        relative: name.to_owned(),
        absolute: tree.path().join(name),
    }
}

fn facts_line(path: &Path, lines: &[usize]) -> String {
    let reports: Vec<String> = lines
        .iter()
        .map(|line| {
            format!("{{\"rule\":\"sa1019\",\"line\":{line},\"column\":2,\"subject\":\"io/ioutil.ReadFile\"}}")
        })
        .collect();
    format!(
        "{{\"file\":{},\"reports\":[{},{{\"rule\":\"otra\",\"line\":1,\"column\":1}}]}}\n",
        serde_json::to_string(&path.display().to_string()).expect("la ruta es texto"),
        reports.join(",")
    )
}

#[test]
fn direct_reports_respect_limits_generated_files_and_nolint() {
    let tree = TempTree::new("go-direct-reports");
    tree.write("go.mod", "module a\n");
    tree.write("a.go", SOURCE);
    tree.write("gen.go", GENERATED);
    tree.write("off.go", SOURCE);
    let (a, generated, off) = (
        identity(&tree, "a.go"),
        identity(&tree, "gen.go"),
        identity(&tree, "off.go"),
    );
    let lines = [
        facts_line(&a.absolute, &[6, 7]),
        facts_line(&generated.absolute, &[5]),
        facts_line(&off.absolute, &[6]),
    ]
    .concat();
    let modules: HashMap<&Path, ModuleFacts> = HashMap::from([(tree.path(), ModuleFacts::parse(&lines))]);
    let roots: HashMap<PathBuf, PathBuf> = [&a, &generated, &off]
        .iter()
        .map(|identity| (identity.absolute.clone(), tree.path().to_path_buf()))
        .collect();
    let strict = Preset::Strict.limits(Language::Go, false);
    assert!(wants_direct_reports(&strict));
    let without = DIRECT_RULES
        .into_iter()
        .fold(strict, |limits, rule| limits.with_rule(RuleId::Go(rule), None));
    assert!(!wants_direct_reports(&without));
    let files = [
        DirectFile {
            identity: &a,
            limits: strict,
        },
        DirectFile {
            identity: &generated,
            limits: strict,
        },
        DirectFile {
            identity: &off,
            limits: without,
        },
    ];
    let (kept, suppressed) = direct_reports(&files, &roots, &modules);
    let positions: Vec<(String, usize)> = kept
        .iter()
        .map(|diagnostic| (diagnostic.relative_path.clone(), diagnostic.line))
        .collect();
    assert_eq!(positions, [("a.go".to_owned(), 6)]);
    assert_eq!(suppressed.len(), 1);
}
